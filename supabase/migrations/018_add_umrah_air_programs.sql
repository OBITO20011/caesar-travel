-- Split Umrah packages into land/air programs and seed the August air offers.
-- Existing Umrah rows remain land programs. Seed rows never overwrite later CMS edits.

ALTER TABLE public.trips
  ADD COLUMN IF NOT EXISTS umrah_transport TEXT
    CHECK (umrah_transport IS NULL OR umrah_transport IN ('land', 'air')),
  ADD COLUMN IF NOT EXISTS umrah_route TEXT
    CHECK (umrah_route IS NULL OR umrah_route IN ('makkah', 'makkah_madinah')),
  ADD COLUMN IF NOT EXISTS single_price NUMERIC(12, 2)
    CHECK (single_price IS NULL OR single_price >= 0),
  ADD COLUMN IF NOT EXISTS flight_details TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS program_inclusions TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS program_requirements TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS program_notes TEXT[] NOT NULL DEFAULT '{}';

UPDATE public.trips
SET umrah_transport = 'land'
WHERE page_key = 'umrah'
  AND umrah_transport IS NULL;

CREATE INDEX IF NOT EXISTS trips_umrah_program_idx
  ON public.trips (umrah_transport, umrah_route, start_date)
  WHERE page_key = 'umrah';

